// 5. Increment & Decrement Operators (Pre & Post Operators)


// 6. Ternary Operator (Short form of if-else)
// Synatx: condtion ? trueValue : falseValue;

let age = 16;
let result = age >=18 ? "Adult": "Minor"; 
console.log(result);

// 7. Nullish Coalescing Operator(??)
// Returns right value only if left value is null or undefined.

let username = null;
console.log(username ?? "Mali");

// 8. Optional Chaining(?.)
let user = {};
console.log(user.address?.city);

// 9. Type Operators
console.log(typeof "Bhavesh");
console.log(typeof 100);
console.log(typeof true);







